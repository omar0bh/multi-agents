import base64
import logging
from pathlib import Path
import httpx

from app.config import GEMINI_API_KEY

logger = logging.getLogger(__name__)

GEMINI_MODEL = "models/gemini-2.5-flash"


def analyze_audio_with_gemini(
    audio_bytes_or_path: bytes | str | Path,
    prompt: str = "Listen carefully to this audio/voice note. Transcribe what was said, and provide a direct, clear, and helpful answer to the user in the exact same language they spoke (Darija, Arabic, English, or French).",
    mime_type: str = "audio/ogg",
) -> dict:
    """Send voice note / audio to Gemini API and return transcription and answer."""
    if not GEMINI_API_KEY:
        return {"ok": False, "error": "Missing GEMINI_API_KEY in .env."}

    if isinstance(audio_bytes_or_path, (str, Path)):
        p = Path(audio_bytes_or_path).expanduser().resolve()
        if not p.is_file():
            return {"ok": False, "error": f"Audio file not found: {audio_bytes_or_path}"}
        audio_bytes = p.read_bytes()
        suffix = p.suffix.lower()
        if suffix in (".mp3", ".mpeg"):
            mime_type = "audio/mp3"
        elif suffix in (".wav", ".wave"):
            mime_type = "audio/wav"
        elif suffix in (".ogg", ".oga"):
            mime_type = "audio/ogg"
    else:
        audio_bytes = audio_bytes_or_path

    b64_data = base64.b64encode(audio_bytes).decode("utf-8")

    # Use v1beta endpoint with gemini-2.5-flash or gemini-1.5-flash
    url = f"https://generativelanguage.googleapis.com/v1beta/{GEMINI_MODEL}:generateContent?key={GEMINI_API_KEY}"
    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt},
                    {
                        "inlineData": {
                            "mimeType": mime_type,
                            "data": b64_data,
                        }
                    },
                ]
            }
        ]
    }

    try:
        with httpx.Client(timeout=45.0) as client:
            resp = client.post(url, json=payload)
            if resp.status_code != 200:
                # Try fallback model if 2.5 is not available
                fallback_url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={GEMINI_API_KEY}"
                fallback_resp = client.post(fallback_url, json=payload)
                if fallback_resp.status_code == 200:
                    resp = fallback_resp
                else:
                    return {
                        "ok": False,
                        "status_code": resp.status_code,
                        "error": f"Gemini Audio API error: {resp.text}",
                    }

            data = resp.json()
            candidates = data.get("candidates", [])
            if not candidates:
                return {"ok": False, "error": "No response generated by Gemini."}

            text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
            return {
                "ok": True,
                "text": text,
                "model": GEMINI_MODEL,
            }
    except Exception as exc:
        logger.exception("Failed to analyze audio with Gemini: %s", exc)
        return {"ok": False, "error": str(exc)}
